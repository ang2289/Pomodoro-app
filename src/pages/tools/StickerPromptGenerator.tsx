function getDefaultText(type: TemplateKey, grid: GridType) {
  return templates[type].texts.slice(0, gridOptions[grid].count).join("\n");
}

function normalizeLines(textArea: string, count: number) {
  const lines = textArea
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
  return lines.slice(0, count);
}

