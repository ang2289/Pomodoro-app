function applyNameToLine(line: string, nameMode: NameMode, rawName: string) {
  const name = rawName.trim();
  const baseLine = stripDemoName(line).trim();

  if (nameMode === "none" || !name) return baseLine;

  const replaced = line.replace(/小宇/g, name);
  if (replaced.includes(name)) return replaced;

  return `${name}${baseLine}`;
}

function getDefaultTextWithName(
  type: TemplateKey,
  grid: GridType,
  nameMode: NameMode,
  customName: string,
) {
  return templates[type].texts
    .slice(0, gridOptions[grid].count)
    .map((line) => applyNameToLine(line, nameMode, customName))
    .join("\n");
}

